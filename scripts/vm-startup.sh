#!/bin/bash
# VM Startup Script for Theorem Marketplace
#
# This script runs on VM boot to:
#   1. Fetch secrets from Google Cloud Secret Manager
#   2. Generate configuration files
#   3. Start all Docker containers
#
# Installation:
#   Set this as the VM's startup script in GCE console or via:
#   gcloud compute instances add-metadata INSTANCE_NAME \
#     --metadata-from-file startup-script=scripts/vm-startup.sh
#
# Prerequisites:
#   - VM service account needs roles/secretmanager.secretAccessor
#   - Docker and docker-compose installed
#   - Repository cloned to /home/vadim/theorem-marketplace

set -euo pipefail

# Configuration
PROJECT_ID="lean-proof-checker"
APP_DIR="/home/vadim/theorem-marketplace"
APP_USER="vadim"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"
}

# Fetch a secret from Secret Manager
get_secret() {
    local name="$1"
    gcloud secrets versions access latest --secret="$name" --project="$PROJECT_ID" 2>/dev/null || echo ""
}

log "Starting Theorem Marketplace setup..."

# Fetch all secrets
log "Fetching secrets from Secret Manager..."
CL_POSTGRES_PASSWORD=$(get_secret "theorem-cl-postgres-password")
THEOREM_POSTGRES_PASSWORD=$(get_secret "theorem-postgres-password")
CONTRACT_ADDRESS=$(get_secret "theorem-contract-address")
HTTP_PROVIDER=$(get_secret "theorem-http-provider")
ADMIN_EMAIL=$(get_secret "theorem-admin-email")
SENDER_EMAIL=$(get_secret "theorem-sender-email")
AWS_REGION=$(get_secret "theorem-aws-region")
AWS_ACCESS_KEY_ID=$(get_secret "theorem-aws-access-key-id")
AWS_SECRET_ACCESS_KEY=$(get_secret "theorem-aws-secret-access-key")
CHAINLINK_KEYSTORE_PASSWORD=$(get_secret "theorem-chainlink-keystore-password")
INFURA_PROJECT_ID=$(get_secret "theorem-infura-project-id")

# Validate critical secrets
if [ -z "$THEOREM_POSTGRES_PASSWORD" ]; then
    log "ERROR: Failed to fetch secrets. Check Secret Manager permissions."
    exit 1
fi

log "Secrets fetched successfully."

# Generate .env file for docker-compose
log "Generating .env file..."
cat > "$APP_DIR/.env" <<EOF
# Auto-generated by vm-startup.sh - DO NOT EDIT
# Secrets are fetched from Google Cloud Secret Manager

CL_POSTGRES_PASSWORD=$CL_POSTGRES_PASSWORD
THEOREM_POSTGRES_PASSWORD=$THEOREM_POSTGRES_PASSWORD
CONTRACT_ADDRESS=$CONTRACT_ADDRESS
HTTP_PROVIDER=$HTTP_PROVIDER
ADMIN_EMAIL=$ADMIN_EMAIL
SENDER_EMAIL=$SENDER_EMAIL
AWS_REGION=$AWS_REGION
AWS_ACCESS_KEY_ID=$AWS_ACCESS_KEY_ID
AWS_SECRET_ACCESS_KEY=$AWS_SECRET_ACCESS_KEY
SYNC_FROM_BLOCK=0
EOF

chown "$APP_USER:$APP_USER" "$APP_DIR/.env"
chmod 600 "$APP_DIR/.env"

# Generate Chainlink secrets.toml
log "Generating Chainlink secrets.toml..."
cat > "$APP_DIR/chainlink/secrets.toml" <<EOF
# Auto-generated by vm-startup.sh - DO NOT EDIT

[Password]
Keystore = '$CHAINLINK_KEYSTORE_PASSWORD'

[Database]
URL = 'postgresql://postgres:$CL_POSTGRES_PASSWORD@cl-postgres:5432/postgres?sslmode=disable'
EOF

chown "$APP_USER:$APP_USER" "$APP_DIR/chainlink/secrets.toml"
chmod 600 "$APP_DIR/chainlink/secrets.toml"

# Update Chainlink config.toml with Infura project ID
log "Updating Chainlink config.toml..."
sed -i "s|YOUR_INFURA_PROJECT_ID|$INFURA_PROJECT_ID|g" "$APP_DIR/chainlink/config.toml"

# Ensure submodules are initialized
log "Initializing git submodules..."
cd "$APP_DIR"
sudo -u "$APP_USER" git submodule update --init --recursive || true

# Start Docker containers
log "Starting Docker containers..."
cd "$APP_DIR"
docker-compose pull --ignore-pull-failures || true
docker-compose up -d

# Wait for services to be healthy
log "Waiting for services to start..."
sleep 30

# Check container status
log "Container status:"
docker-compose ps

log "Theorem Marketplace startup complete!"
